"""Local-first LLM provider backed by Ollama (http://localhost:11434 by
default). This is the default provider ToneForge AI ships with - no cloud
dependency, works fully offline once a model is pulled (docs/ROADMAP.md M6).

Reliability strategy: local models are not guaranteed to emit valid JSON on
the first try. We ask for JSON explicitly, validate the response against
PresetDTO, and retry a bounded number of times with a corrective prompt
before giving up. Callers (routes) are expected to fall back to MockProvider
on ProviderUnavailableError so a bad/missing model degrades gracefully
instead of breaking the AI panel.
"""

from __future__ import annotations

import copy
import json
from typing import Any

import httpx
from pydantic import ValidationError

from app.core.mapping import descriptor_to_preset
from app.core.tone_descriptor import descriptor_from_text
from app.providers.base import ProviderUnavailableError
from app.schemas.preset import AiProvenanceDTO, PresetDTO

# Categorical fields are requested as short strings, not raw integers - a
# local model is far more reliably able to emit "spring" than to remember
# that spring is index 2 out of 4. _merge_descriptor() below maps the
# string back onto the int/str values ToneDescriptor actually stores,
# falling back to the keyword-derived baseline (never raising) if the model
# emits something unrecognized.
#
# The trailing "Examples" block is few-shot prompting, added after the
# fine-tuning path (docs/ROADMAP.md's M6/M7 log - the "fine-tuning shelved"
# entry) was shelved as too much setup/training time for an uncertain
# payoff. This is the free alternative: no training, no new data - the 4
# examples below were generated by running real prompts through
# descriptor_from_text() (scripts/generate_training_data.py does the same
# thing for the fine-tuning dataset that never shipped) so every example's
# JSON is guaranteed internally consistent with its prompt, not hand-typed
# and possibly wrong. Chosen to span the parameter space (clean vs. heavy
# gain, dry vs. maximal ambience, a categorical-field-heavy example) rather
# than cluster around one style, so the model sees the full range of valid
# outputs, not just one shape of answer.
